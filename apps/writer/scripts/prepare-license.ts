/**
 * Writes the Syncfusion licence key, read from the environment, into a generated module (ADR-005).
 *
 * The key is never committed: `src/generated` is ignored. Without the variable the module holds an empty key, the
 * application still builds, and Syncfusion shows its own licence banner, which the application never hides.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const out = join(root, 'apps/writer/src/generated');

const key = (process.env['SYNCFUSION_UI_LICENSE_KEY'] ?? '').trim();

mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, 'license.ts'),
  `/** Generated by scripts/prepare-license.ts from SYNCFUSION_UI_LICENSE_KEY. Do not edit or commit. */\nexport const SYNCFUSION_LICENSE_KEY: string = ${JSON.stringify(key)};\n`,
);
console.log(
  key === ''
    ? 'No SYNCFUSION_UI_LICENSE_KEY set; the licence banner will show.'
    : 'Wrote the Syncfusion licence key module.',
);
